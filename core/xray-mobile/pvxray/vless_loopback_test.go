// Reserve a test-only localhost port. These tests do not contact the Internet
// and do not use a production VPN server or customer credentials.
func freeLoopbackPort(t *testing.T) int {
    t.Helper()
    l, err := net.Listen("tcp", "127.0.0.1:0")
    if err != nil { t.Fatal(err) }
    port := l.Addr().(*net.TCPAddr).Port
    if err := l.Close(); err != nil { t.Fatal(err) }
    return port
}

func TestDartGeneratedVlessHasRealLocalHandshakeAndDataPath(t *testing.T) {
    if os.Getenv("PV_REQUIRE_XRAY_FIXTURES") != "1" {
        t.Skip("requires synthetically generated Dart VLESS config from CI")
    }
    const userID = "00000000-0000-4000-8000-000000000001"

    // The HTTP target is local, and returns a unique marker only after an
    // actual VLESS server handshake and HTTP request have traversed Xray.
    target := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
        if r.URL.Path != "/pvnetwork-vless-proof" {
            http.Error(w, "unexpected request", http.StatusNotFound)
            return
        }
        w.Header().Set("X-PVNetwork-Interop", "loopback-vless")
        _, _ = io.WriteString(w, "PVNETWORK_VLESS_REAL_DATA_PATH_OK")
    }))
    defer target.Close()

    vlessPort := freeLoopbackPort(t)
    socksPort := freeLoopbackPort(t)
    if socksPort == vlessPort { socksPort = freeLoopbackPort(t) }

    // Disposable local Xray server. Never expose this no-TLS fixture on a
    // public interface. The real product refuses insecure public VLESS.
    serverConfig := map[string]any{
        "log": map[string]any{"loglevel": "warning"},
        "inbounds": []any{map[string]any{
            "listen": "127.0.0.1",
            "port": vlessPort,
            "protocol": "vless",
            "settings": map[string]any{
                "decryption": "none",
                "clients": []any{map[string]any{"id": userID}},
            },
        }},
        "outbounds": []any{map[string]any{
            "tag": "direct", "protocol": "freedom", "settings": map[string]any{},
        }},
    }
    serverBytes, err := json.Marshal(serverConfig)
    if err != nil { t.Fatal(err) }
    server, err := core.StartInstance("json", serverBytes)
    if err != nil { t.Fatalf("local Xray server could not start: %v", err) }
    defer func() { _ = server.Close() }()

    // Keep Flutter's actual outbound generated by XrayConfigBuilder. Replace
    // its mobile TUN inbound with a local SOCKS inbound so this test can
    // operate without Android VpnService or any special kernel privilege.
    raw, err := os.ReadFile(filepath.Join("..", "config-fixtures", "vless-loopback.json"))
    if err != nil { t.Fatalf("mandatory Dart-generated profile missing: %v", err) }
    var clientConfig map[string]any
    if err := json.Unmarshal(raw, &clientConfig); err != nil { t.Fatal(err) }
    outbounds, ok := clientConfig["outbounds"].([]any)
    if !ok || len(outbounds) == 0 { t.Fatal("Dart produced no Xray outbound") }
    first, ok := outbounds[0].(map[string]any)
    if !ok || first["protocol"] != "vless" { t.Fatal("Dart outbound is not VLESS") }
    settings, ok := first["settings"].(map[string]any)
    if !ok || settings["id"] != userID {
        t.Fatal("Dart-generated VLESS outbound lost expected test credentials")
    }
    settings["address"] = "127.0.0.1"
    settings["port"] = vlessPort
    clientConfig["inbounds"] = []any{map[string]any{
        "listen": "127.0.0.1", "port": socksPort, "protocol": "socks",
        "settings": map[string]any{"auth": "noauth", "udp": false},
    }}
    // Route to the default first (Dart) VLESS outbound, even for the
    // private localhost HTTP target. The production client keeps LAN bypass.
    delete(clientConfig, "routing")
    clientBytes, err := json.Marshal(clientConfig)
    if err != nil { t.Fatal(err) }
    client, err := core.StartInstance("json", clientBytes)
    if err != nil { t.Fatalf("Dart-generated Xray client could not start: %v", err) }
    defer func() { _ = client.Close() }()

    socksAddress, err := url.Parse(fmt.Sprintf("socks5://127.0.0.1:%d", socksPort))
    if err != nil { t.Fatal(err) }
    transport := &http.Transport{Proxy: http.ProxyURL(socksAddress)}
    defer transport.CloseIdleConnections()
    httpClient := &http.Client{Transport: transport, Timeout: 8 * time.Second}
    response, err := httpClient.Get(target.URL + "/pvnetwork-vless-proof")
    if err != nil {
        t.Fatalf("request through real local VLESS Xray chain failed: %v", err)
    }
    defer response.Body.Close()
    payload, err := io.ReadAll(io.LimitReader(response.Body, 256))
    if err != nil { t.Fatal(err) }
    if response.StatusCode != http.StatusOK ||
        response.Header.Get("X-PVNetwork-Interop") != "loopback-vless" ||
        string(payload) != "PVNETWORK_VLESS_REAL_DATA_PATH_OK" {
        t.Fatalf("invalid response after VLESS handshake: status=%d body=%q",
            response.StatusCode, string(payload))
    }
}
